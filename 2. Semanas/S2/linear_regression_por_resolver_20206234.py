"""# Optimización

## Gradients

$ \frac{dL}{da} = \sum\limits_{i=1}^m (f(x_i) - y_i)(x_i)$

$ \frac{dL}{db} = \sum\limits_{i=1}^m (f(x_i) - y_i)$
"""

def gradients(x, y, y_):
    da = ((y_ - y) * x).mean()
    db = (y_ - y).mean()
    return da, db

gradients(x, y, y_)

