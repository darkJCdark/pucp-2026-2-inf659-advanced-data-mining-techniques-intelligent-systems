"""## PyTorch"""

import torch
import numpy as np

np.random.seed(0)

x = np.arange(100)/100
y = x + np.random.normal(scale=0.05, size=100)

#Agregamos 1's en la primera columna al arreglo de x
x = np.array([np.array([1, i]) for i in x])

y = y.reshape((-1, 1))

"""Calcular $ z = (x^{T} x)^{-1} x^{T}y $"""

# Convertimos los arreglos a tensores de PyTorch con tipo float32
x_tensor = torch.tensor(x, dtype=torch.float32)
y_tensor = torch.tensor(y, dtype=torch.float32)

# Transpuesta de la matriz bidimensional
x_t = x_tensor.transpose(0, 1)

# Producto matricial e inversa usando la función
x_tx = x_t @ x_tensor
x_tx_inv = x_tx.inverse()

# Cálculo final de z
z = x_tx_inv @ x_t @ y_tensor
print(z)