import numpy as np

np.random.seed(0)

x = np.arange(100)/100
y = x + np.random.normal(scale=0.05, size=100)

#Agregamos 1's en la primera columna al arreglo de x
x = np.array([np.array([1, i]) for i in x])

y = y.reshape((-1, 1))

"""Calcular $ z = (x^{T} x)^{-1} x^{T}y $"""

# Se calcula la transpuesta de x
x_t = x.T

# Producto matricial (x^T * x)
x_tx = x_t @ x

# Inversa del producto
x_tx_inv = np.linalg.inv(x_tx)

# Cálculo final de z
z = x_tx_inv @ x_t @ y
print(z)

