def intercambiar(frase, rng):
    pares = [(i, j) for i in range(len(frase)) for j in range(i + 1, len(frase)) if frase[i] != frase[j]]
    i, j = rng.choice(pares)
    f = list(frase)
    f[i], f[j] = f[j], f[i]
    return tuple(f)


