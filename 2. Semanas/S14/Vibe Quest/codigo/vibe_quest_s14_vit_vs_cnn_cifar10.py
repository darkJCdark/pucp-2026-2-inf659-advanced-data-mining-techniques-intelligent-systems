"""# 4 · Extracción de rasgos
Cada imagen de 32×32 se agranda a 224×224 (interpolación bicúbica) y se normaliza con la media y desviación propias de cada modelo. Luego pasa por el extractor congelado y guardamos el vector de rasgos. Se extrae **una sola vez** para las 60000 imágenes; después todas las sondas trabajan sobre esos vectores, lo que hace barato probar muchos tamaños y semillas.

## 4.1 · Función de extracción
"""

@torch.no_grad()
def extraer(modelo, cfg, X):
    media = torch.tensor(cfg["mean"], device=DEVICE).view(1, 3, 1, 1)
    desv = torch.tensor(cfg["std"], device=DEVICE).view(1, 3, 1, 1)
    salidas = []
    for i in range(0, len(X), BATCH):
        lote = torch.from_numpy(X[i:i + BATCH]).to(DEVICE).permute(0, 3, 1, 2).float() / 255
        lote = F.interpolate(lote, size=224, mode="bicubic", align_corners=False).clamp(0, 1)
        lote = (lote - media) / desv
        with torch.autocast("cuda", dtype=torch.float16):    # media precisión: más rápido y suficiente aquí
            f = modelo(lote)
        salidas.append(f.float().cpu())
    return torch.cat(salidas)

"""## 4.2 · Extraer los rasgos de CIFAR-10
Tarda unos dos o tres minutos en una T4. Medimos el tiempo y la memoria máxima de cada modelo para la comparación de eficiencia.
"""

