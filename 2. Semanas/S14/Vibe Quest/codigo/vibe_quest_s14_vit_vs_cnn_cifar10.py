"""## 8.6 · Qué frecuencias conserva cada arquitectura (análisis de Fourier)
Park y Kim (2022, sec. 3 y apéndice A.2, p. 16) miden la diferencia entre la amplitud logarítmica de la frecuencia más alta (1.0π) y la de frecuencia cero en los mapas de características, a lo largo de la profundidad. Concluyen que las capas de atención actúan como filtros pasa-bajos y las convoluciones como pasa-altos, en redes entrenadas desde cero.

Aquí repetimos la medición con los modelos preentrenados, con tres diferencias respecto de su procedimiento que hay que tener presentes: usamos 512 imágenes de prueba (ellos usan todo el conjunto de prueba), una ventana de frecuencias de ±0.125π (ellos usan 0.1π; con mapas de 7×7 una ventana más estrecha queda vacía) y la salida de cada bloque completo (ellos separan atención y MLP). Se grafican cuatro frecuencias, no solo 1.0π, y se toman los 12 bloques del ViT y los 18 bloques de ConvNeXt.

Una curva que baja con la profundidad significa que esa frecuencia pierde peso respecto de la media del mapa. Es una descripción de estos pesos concretos, no una prueba de que la atención suavice ni de que la convolución realce.
"""

FRECUENCIAS = [0.25, 0.5, 0.75, 1.0]      # fracción de la frecuencia máxima (π)
VENTANA = 0.125                           # semiancho del anillo de frecuencias, en fracción de π
N_IMG_ESPECTRO = 512                      # imágenes de prueba usadas para promediar el espectro

def delta_log_amplitud(mapa):
    # mapa: (B, C, H, W). Devuelve log(amplitud en f) − log(amplitud en f = 0) para cada frecuencia
    B, Cn, H, W = mapa.shape
    amp = torch.fft.fft2(mapa).abs()
    fy = torch.fft.fftfreq(H).view(H, 1)
    fx = torch.fft.fftfreq(W).view(1, W)
    radio = torch.sqrt(fy ** 2 + fx ** 2) / 0.5          # 1.0 = frecuencia de Nyquist
    dc = amp[:, :, 0, 0].mean()
    res = []
    for f in FRECUENCIAS:
        anillo = (radio >= f - VENTANA) & (radio < f + VENTANA)
        res.append((torch.log(amp[:, :, anillo].mean()) - torch.log(dc)).item())
    return res

def espectro_por_capa(imagenes, lote=16):
    # Para cada capa guarda Δ log amplitud promediado en lotes de imágenes
    vit_acum, cnn_acum, n_lotes = None, None, 0
    for i in range(0, len(imagenes), lote):
        x = torch.cat([preparar(j) for j in imagenes[i:i + lote]])
        bl = capturar(vit, list(vit.blocks), normalizar(x, cfg_vit))
        cb = capturar(cnn, [b for et in cnn.stages for b in et.blocks], normalizar(x, cfg_cnn))
        v = np.array([delta_log_amplitud(t[:, 1:].permute(0, 2, 1).reshape(len(t), -1, 14, 14)) for t in bl])
        c = np.array([delta_log_amplitud(t) for t in cb])
        vit_acum = v if vit_acum is None else vit_acum + v
        cnn_acum = c if cnn_acum is None else cnn_acum + c
        n_lotes += 1
    return vit_acum / n_lotes, cnn_acum / n_lotes

