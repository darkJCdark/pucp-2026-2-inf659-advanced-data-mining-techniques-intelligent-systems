"""# 5 · Sonda lineal con 100, 1000 y 10000 imágenes
Para cada modelo, tamaño y semilla: se elige un subconjunto **balanceado** del entrenamiento (el mismo número de imágenes por clase), se estandarizan los rasgos con la media y la desviación de ese subconjunto y se entrena una regresión logística multinomial con penalización L2. La penalización se elige por validación cruzada de 3 particiones **dentro del subconjunto**, nunca con las imágenes de prueba. Los dos modelos reciben exactamente el mismo trato, como indica la lámina 99 de la Clase 14 (comparar arquitecturas exige igualar la receta de entrenamiento).

## 5.1 · Muestreo balanceado
"""

def muestrear(y, n, semilla):
    # Elige n // (número de clases) imágenes por clase, al azar según la semilla
    rng = np.random.default_rng(semilla)
    clases = np.unique(y)
    por_clase = n // len(clases)
    return np.concatenate([rng.choice(np.where(y == k)[0], por_clase, replace=False) for k in clases])

"""## 5.2 · Sonda lineal en la GPU
Regresión logística multinomial entrenada con L-BFGS sobre todo el subconjunto a la vez (con tan pocos datos no hace falta hacer lotes).
"""

def ajustar_sonda(X, y, lam, n_clases, iteraciones=200):
    # W y b son los únicos parámetros que se aprenden; el extractor sigue congelado
    W = torch.zeros(X.shape[1], n_clases, device=DEVICE, requires_grad=True)
    b = torch.zeros(n_clases, device=DEVICE, requires_grad=True)
    opt = torch.optim.LBFGS([W, b], lr=1, max_iter=iteraciones, line_search_fn="strong_wolfe")

    def cierre():
        opt.zero_grad()
        perdida = F.cross_entropy(X @ W + b, y) + lam * (W ** 2).sum()   # entropía cruzada + penalización L2
        perdida.backward()
        return perdida

    opt.step(cierre)
    return W.detach(), b.detach()

def elegir_lambda(X, y, n_clases):
    # Validación cruzada estratificada de 3 particiones: se queda con la penalización que más acierta
    kf = StratifiedKFold(n_splits=3, shuffle=True, random_state=0)
    particiones = list(kf.split(np.zeros(len(y)), y.cpu().numpy()))
    puntajes = {}
    for lam in LAMBDAS:
        aciertos = []
        for tr, va in particiones:
            W, b = ajustar_sonda(X[tr], y[tr], lam, n_clases)
            aciertos.append(((X[va] @ W + b).argmax(1) == y[va]).float().mean().item())
        puntajes[lam] = float(np.mean(aciertos))
    return max(puntajes, key=puntajes.get)

def evaluar_sonda(F_tr, y_tr, F_te, n, semilla, n_clases):
    # Un experimento completo: muestrear, estandarizar, elegir lambda, entrenar y predecir en prueba
    idx = muestrear(y_tr, n, semilla)
    Xs = F_tr[idx]
    ys = torch.from_numpy(y_tr[idx]).to(DEVICE)
    mu, sd = Xs.mean(0), Xs.std(0) + 1e-6          # estandarización con el subconjunto de entrenamiento
    Xs = ((Xs - mu) / sd).to(DEVICE)
    lam = elegir_lambda(Xs, ys, n_clases)
    W, b = ajustar_sonda(Xs, ys, lam, n_clases)
    Xt = ((F_te - mu) / sd).to(DEVICE)
    pred = (Xt @ W + b).argmax(1).cpu().numpy()
    return {"pred": pred, "lam": lam, "W": W.cpu(), "b": b.cpu(), "mu": mu, "sd": sd, "idx": idx}

def barrer(feats, y_tr, y_te, n_clases, tamanos):
    # Recorre modelos × tamaños × semillas y junta exactitudes y predicciones
    filas, preds, sondas = [], {}, {}
    for nombre in MODELOS:
        for n in tamanos:
            for s in SEMILLAS:
                r = evaluar_sonda(feats[(nombre, "train")], y_tr, feats[(nombre, "test")], n, s, n_clases)
                preds[(nombre, n, s)] = r["pred"]
                if s == SEMILLAS[0]:                      # solo guardamos los pesos de la primera semilla
                    sondas[(nombre, n)] = r               # (los usan los mapas de Grad-CAM de la sección 8)
                filas.append({"modelo": nombre, "n": n, "semilla": s,
                              "exactitud": float((r["pred"] == y_te).mean()), "lambda": r["lam"]})
    return pd.DataFrame(filas), preds, sondas

