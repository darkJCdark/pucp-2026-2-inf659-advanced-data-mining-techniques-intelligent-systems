"""# 8 · ¿Dónde mira cada modelo? Mapas de atención frente a mapas de características
Un ViT y una CNN "miran" de maneras distintas, y por eso no se pueden dibujar con el mismo método:

- **ViT.** Tiene matrices de atención. Dibujamos el *attention rollout* (Abnar y Zuidema, 2020, pp. 3–4: se suma la identidad a la atención, A = 0.5·W + 0.5·I, y se multiplican las capas), que combina la atención de todas las capas teniendo en cuenta las conexiones residuales, y también la atención directa del token [CLS] en una capa y cabeza concretas.
- **CNN.** No tiene atención: lo que tiene son mapas de características (la salida de cada etapa). Dibujamos su magnitud y sus tres primeras componentes principales (PCA) como color.
- **Los dos.** Aplicamos **Grad-CAM** (Selvaraju et al., 2017, ec. 1, p. 4: pesos por promedio global de los gradientes y ReLU de la suma ponderada), que usa el gradiente de la clase elegida respecto a las activaciones y funciona igual en ambas arquitecturas. Aquí el "puntaje" de la clase es el de la sonda lineal entrenada en la sección 5, de modo que se puede ver cómo cambia el mapa según con cuántas imágenes se entrenó la sonda.

Rollout y Grad-CAM son anteriores a 2022; los incluimos como excepción acordada, porque son los métodos originales. Park y Kim (2022) usan además el análisis de Fourier de los mapas de características, que retomamos en la sección 8.6.

## 8.1 · Preparar los modelos y las funciones de captura
"""

vit, cfg_vit = MOD["ViT-S/16"]
cnn, cfg_cnn = MOD["ConvNeXt-T"]

# La atención "fusionada" de timm no devuelve la matriz de atención: se desactiva para poder leerla
for bloque in vit.blocks:
    bloque.attn.fused_attn = False
N_CABEZAS = vit.blocks[0].attn.num_heads
print("bloques del ViT:", len(vit.blocks), "| cabezas por bloque:", N_CABEZAS, "| etapas de ConvNeXt:", len(cnn.stages))

def preparar(i):
    # Imagen de prueba i, agrandada a 224×224 y sin normalizar (sirve para dibujarla)
    x = torch.from_numpy(Xte[i]).permute(2, 0, 1).float().div(255)[None].to(DEVICE)
    return F.interpolate(x, size=224, mode="bicubic", align_corners=False).clamp(0, 1)

def normalizar(x, cfg):
    media = torch.tensor(cfg["mean"], device=DEVICE).view(1, 3, 1, 1)
    desv = torch.tensor(cfg["std"], device=DEVICE).view(1, 3, 1, 1)
    return (x - media) / desv

def capturar(modelo, capas, x_norm):
    # Pasa la imagen por el modelo y guarda la salida de cada capa de la lista
    salidas, ganchos = [], []
    for capa in capas:
        ganchos.append(capa.register_forward_hook(lambda m, i, o: salidas.append(o.detach().float().cpu())))
    with torch.no_grad():
        modelo(x_norm)
    for g in ganchos:
        g.remove()
    return salidas

"""## 8.2 · Attention rollout y mapas de características
El rollout se calcula así: en cada capa se promedia la atención de todas las cabezas, se suma la identidad (para representar la conexión residual) y se normaliza cada fila; el producto de las matrices de todas las capas dice cuánta información de cada parche llega al token [CLS].
"""

def rollout(atenciones):
    # atenciones: lista de tensores (cabezas, N, N), una por capa
    n = atenciones[0].shape[-1]
    R = torch.eye(n)
    for A in atenciones:
        a = A.mean(0) + torch.eye(n)            # promedio de cabezas + conexión residual
        a = a / a.sum(-1, keepdim=True)         # cada fila vuelve a sumar 1
        R = a @ R                               # se acumula capa tras capa
    return R[0, 1:].reshape(14, 14)             # fila del [CLS] hacia los 14×14 parches

def mapa_pca(feat_hwc):
    # Resume los canales en 3 componentes principales y los usa como color RGB
    h, w, c = feat_hwc.shape
    X = feat_hwc.reshape(-1, c)
    X = X - X.mean(0)
    _, _, V = torch.pca_lowrank(X, q=3)
    P = X @ V[:, :3]
    P = (P - P.min(0).values) / (P.max(0).values - P.min(0).values + 1e-8)
    return P.reshape(h, w, 3)

def vista_vit(x_norm):
    # Todo lo que se dibuja del ViT para una imagen
    atenciones = [a[0] for a in capturar(vit, [b.attn.attn_drop for b in vit.blocks], x_norm)]   # (cabezas, 197, 197)
    bloques = capturar(vit, list(vit.blocks), x_norm)                                              # (1, 197, 384)
    return atenciones, bloques

def vista_cnn(x_norm):
    return capturar(cnn, list(cnn.stages), x_norm)                                                 # (1, C, H, W) por etapa

"""## 8.3 · Grad-CAM con la sonda lineal
Para el ViT usamos la entrada de la atención del último bloque (`blocks[-1].norm1`): en la salida del último bloque solo importa el token [CLS], así que los parches no tendrían gradiente. Para ConvNeXt usamos la salida de la última etapa (7×7). En los dos casos el gradiente es el de la puntuación de la clase en la sonda.
"""

def logits_sonda(rasgos, s):
    # Puntaje de cada clase: estandarizar con los datos del entrenamiento y aplicar W y b de la sonda
    mu, sd, W, b = (s[k].to(DEVICE) for k in ("mu", "sd", "W", "b"))
    return ((rasgos - mu) / sd) @ W + b

def grad_cam(modelo, capa, x_norm, s, clase=None):
    # Devuelve el mapa Grad-CAM, la clase usada y las probabilidades de la sonda
    guardado = {}

    def gancho(modulo, entrada, salida):
        salida.retain_grad()                  # necesitamos el gradiente de esta activación
        guardado["a"] = salida

    g = capa.register_forward_hook(gancho)
    x = x_norm.clone().requires_grad_(True)  # sin esto no se arma el grafo: los pesos están congelados
    z = logits_sonda(modelo(x), s)
    clase = int(z.argmax(1)) if clase is None else clase
    z[0, clase].backward()
    g.remove()
    A, G = guardado["a"][0], guardado["a"].grad[0]
    if A.dim() == 2:                          # ViT: (tokens, canales) → solo parches, sin [CLS]
        A, G = A[1:], G[1:]
        cam = F.relu((A * G.mean(0)).sum(1)).reshape(14, 14)
    else:                                     # CNN: (canales, alto, ancho)
        cam = F.relu((A * G.mean((1, 2))[:, None, None]).sum(0))
    return cam.detach().cpu(), clase, z.softmax(1)[0].detach().cpu()

