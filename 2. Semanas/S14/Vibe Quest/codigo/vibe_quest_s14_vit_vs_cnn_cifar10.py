"""# 6 · ¿La diferencia entre el ViT y la CNN es real?
Con 3 semillas, una prueba t tendría solo 2 grados de libertad. Por eso usamos un **bootstrap sobre las 10000 imágenes de prueba**: se remuestrean las imágenes con reemplazo, se calcula en cada remuestreo la diferencia de exactitud ViT − ConvNeXt (promediada en las 3 semillas) y se toma el intervalo entre percentiles. Si el intervalo no contiene el cero, hay una diferencia clara; si lo contiene, no podemos decir que una arquitectura gane.

**Qué mide y qué no.** El bootstrap captura la incertidumbre por tener solo 10000 imágenes de prueba; no captura la variación por elegir otro subconjunto de entrenamiento (para eso están las desviaciones entre semillas de la sección 5).

## 6.1 · Función de bootstrap
"""

def bootstrap_diferencia(preds, y_te, n, n_boot=N_BOOT, semilla=0):
    # Para cada imagen de prueba: fracción de semillas que acertó cada modelo
    ok_vit = np.stack([preds[("ViT-S/16", n, s)] == y_te for s in SEMILLAS]).mean(0)
    ok_cnn = np.stack([preds[("ConvNeXt-T", n, s)] == y_te for s in SEMILLAS]).mean(0)
    d = ok_vit - ok_cnn
    rng = np.random.default_rng(semilla)
    medias = np.empty(n_boot)
    for i in range(0, n_boot, 250):                    # por bloques para no gastar memoria
        k = min(250, n_boot - i)
        idx = rng.integers(0, len(d), (k, len(d)))
        medias[i:i + k] = d[idx].mean(1)
    return d.mean(), medias

